class MockClassList {
    constructor(element = null) {
        this._set = new Set();
        this._element = element;
    }
    _sync() {
        if (this._element) this._element.className = Array.from(this._set).join(' ');
    }
    add(...classes) {
        for (const c of classes) this._set.add(c);
        this._sync();
    }
    remove(...classes) {
        for (const c of classes) this._set.delete(c);
        this._sync();
    }
    contains(cls) { return this._set.has(cls); }
    has(cls) { return this._set.has(cls); }
    toggle(cls, force) {
        if (force === undefined) { if (this._set.has(cls)) this._set.delete(cls); else this._set.add(cls); }
        else if (force) this._set.add(cls);
        else this._set.delete(cls);
        this._sync();
    }
    [Symbol.iterator]() { return this._set[Symbol.iterator](); }
}

class MockElement {
    constructor(tagName) {
        this.tagName = String(tagName).toUpperCase();
        this.children = [];
        this.style = {};
        this.dataset = {};
        this.classList = new MockClassList(this);
        this.className = '';
        this.id = '';
        this._innerHTML = '';
        this.textContent = '';
        this.value = '';
        this.type = '';
        this.checked = false;
        this.placeholder = '';
        this.parentNode = null;
        this.eventListeners = {};
        this.attributes = {};
    }

    get parentElement() { return this.parentNode; }
    set parentElement(val) { this.parentNode = val; }

    setAttribute(name, val) {
        this.attributes[name] = String(val);
    }

    get innerHTML() {
        return this._innerHTML || '';
    }

    set innerHTML(val) {
        this._innerHTML = val;
        if (val === '') {
            this.children = [];
        }
    }

    appendChild(child) {
        if (!child) return child;
        child.parentNode = this;
        this.children.push(child);
        return child;
    }

    insertBefore(newNode, refNode) {
        const idx = this.children.indexOf(refNode);
        if (idx !== -1) {
            newNode.parentNode = this;
            this.children.splice(idx, 0, newNode);
        } else {
            this.appendChild(newNode);
        }
        return newNode;
    }

    removeChild(child) {
        const idx = this.children.indexOf(child);
        if (idx !== -1) {
            this.children.splice(idx, 1);
            child.parentNode = null;
        }
        return child;
    }

    get nextSibling() {
        if (!this.parentNode) return null;
        const idx = this.parentNode.children.indexOf(this);
        if (idx !== -1 && idx + 1 < this.parentNode.children.length) {
            return this.parentNode.children[idx + 1];
        }
        return null;
    }

    querySelector(selector) {
        return this.querySelectorAll(selector)[0] || null;
    }

    querySelectorAll(selector) {
        const results = [];
        const parts = selector.split(',').map(s => s.trim());
        const match = (el, sel) => {
            if (sel.startsWith('#') && el.id === sel.slice(1)) return true;
            if (sel.startsWith('.')) {
                const classes = sel.slice(1).split('.');
                if (classes.every(cls => el.className.includes(cls) || el.classList.has(cls))) return true;
            }
            if (sel.toLowerCase() === el.tagName.toLowerCase()) return true;
            if (sel === '[role="dialog"]' && el.dataset.role === 'dialog') return true;
            if (sel.includes('container-type: size')) {
                const styleStr = typeof el.style === 'string' ? el.style : (el.style['container-type'] || '');
                if (styleStr.includes('size')) return true;
            }
            return false;
        };

        const traverse = (node) => {
            for (const child of node.children) {
                if (parts.some(p => match(child, p))) results.push(child);
                traverse(child);
            }
        };
        traverse(this);
        return results;
    }

    getAttribute(name) {
        if (name === 'id') return this.id || null;
        if (name === 'role') return this.role || null;
        if (name.startsWith('data-')) {
            const key = name.replace('data-', '').replace(/-([a-z])/g, (_, c) => c.toUpperCase());
            return this.dataset[key] != null ? this.dataset[key] : null;
        }
        return this.attributes ? (this.attributes[name] ?? null) : null;
    }

    closest(selector) {
        let cur = this;
        while (cur) {
            if (selector.toLowerCase() === cur.tagName?.toLowerCase()) return cur;
            if (selector.startsWith('#') && cur.id === selector.slice(1)) return cur;
            if (selector.startsWith('.') && (cur.className?.includes(selector.slice(1)) || cur.classList?.has(selector.slice(1)))) return cur;
            if (selector.startsWith('[') && selector.endsWith(']')) {
                const attr = selector.slice(1, -1);
                const m = attr.match(/^([\w-]+)(?:=["']?([^"']*)["']?)?$/);
                if (m) {
                    const val = cur.getAttribute ? cur.getAttribute(m[1]) : (cur.dataset?.[m[1]] || cur[m[1]]);
                    if (val != null && (m[2] === undefined || String(val) === m[2])) return cur;
                }
            }
            cur = cur.parentNode;
        }
        return null;
    }

    addEventListener(event, fn) {
        if (!this.eventListeners[event]) this.eventListeners[event] = [];
        this.eventListeners[event].push(fn);
    }

    dispatchEvent(event) {
        const handlers = this.eventListeners[event.type] || [];
        for (const h of handlers) h(event);
    }
}

